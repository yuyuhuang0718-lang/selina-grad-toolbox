import assert from 'node:assert/strict';
import { cleanRows, trimAscii, buildOutline, SAMPLE_TSV } from '../assets/tools.mjs';

const sample = cleanRows(SAMPLE_TSV);
assert.equal(sample.inputCount, 4);
assert.equal(sample.rows.length, 3);
assert.equal(sample.duplicateCount, 1);
assert.equal(sample.missing, 1);
assert.equal(sample.rows[2][2], '', 'missing score must not become zero');
assert.deepEqual(cleanRows('ID\t名稱\t分數\n001\t甲\t0').rows, [['001','甲','0']], 'preserve leading zeros and actual zero');
assert.deepEqual(cleanRows('ID\t名稱\t分數\r\n001\t甲\t0\r\n').rows, [['001','甲','0']], 'accept CRLF and trailing newline');
const conflict = cleanRows('ID\t名稱\t分數\nR01\t甲\t85\nR01\t甲\t90');
assert.equal(conflict.rows.length, 2);
assert.deepEqual(conflict.conflicts, ['R01']);
assert.equal(trimAscii(' A   B '), 'A B');
assert.equal(trimAscii('\u00a0A\u00a0'), '\u00a0A\u00a0', 'NBSP is not ASCII space');
assert.throws(() => cleanRows(''), /先貼上/);
assert.throws(() => cleanRows('ID\t名稱\t分數'), /至少/);
assert.throws(() => cleanRows('ID,名稱,分數\n1,甲,85'), /第一列/);
assert.throws(() => cleanRows('ID\t名稱\t分數\n1\t甲'), /不是三欄/);
for (const score of ['NaN', 'Infinity', '-1', '101', '=1+1', '0x10']) assert.throws(() => cleanRows(`ID\t名稱\t分數\n1\t甲\t${score}`), /分數/);
assert.throws(() => cleanRows('ID\t名稱\t分數\n' + Array.from({length:101}, (_,i) => `${i}\t甲\t85`).join('\n')), /最多/);
assert.equal(cleanRows('ID\t名稱\t分數\n1\t<img onerror=alert(1)>\t85').rows[0][1], '<img onerror=alert(1)>', 'user text must remain plain text for DOM rendering');
const outline = buildOutline([{text:'內文',level:0},{text:'孤立小節',level:2},{text:'第一章',level:1},{text:'1.1',level:2}]);
assert.equal(outline.length, 3);
assert.equal(outline[0].orphan, true);
assert.equal(outline[2].orphan, false);
assert.equal(buildOutline([{text:'內文',level:0}]).length, 0);
console.log('Tools OK: sample, missing/zero, IDs, CRLF, conflicts, ASCII/NBSP, invalid input, size limits, plain text, outline hierarchy.');
